bool BulkRenamerEngine::isAutoGeneratedName(const QString& name) {
    static const QRegularExpression re(QStringLiteral("^(?:sub|FUN|func|unnamed|loc)_[0-9a-fA-F]+$"));
    return re.match(name).hasMatch();
}

std::map<uint64_t, QString> BulkRenamerEngine::parseQuickReply(const QString& text) {
    static const QRegularExpression re(QStringLiteral("^0x([0-9a-fA-F]+)\\s+(\\S+)$"),
                                       QRegularExpression::UseUnicodePropertiesOption);
    std::map<uint64_t, QString> out;
    for (const QString& raw : splitLines(text.trimmed())) {
        const QRegularExpressionMatch m = re.match(raw.trimmed());
        if (!m.hasMatch()) continue;
        bool ok = false;
        const uint64_t addr = m.captured(1).toULongLong(&ok, 16);
        if (ok) out[addr] = m.captured(2);
    }
    return out;
}

std::optional<std::pair<uint64_t, QString>> BulkRenamerEngine::parseDeepReply(const QString& text) {
    static const QRegularExpression re(QStringLiteral("RENAME:\\s*0x([0-9a-fA-F]+)\\s+(\\S+)"),
                                       QRegularExpression::UseUnicodePropertiesOption);
    const QRegularExpressionMatch m = re.match(text);
    if (!m.hasMatch()) return std::nullopt;
    bool ok = false;
    const uint64_t addr = m.captured(1).toULongLong(&ok, 16);
    if (!ok) return std::nullopt;
    return std::make_pair(addr, m.captured(2));
}

QString BulkRenamerEngine::quickFunctionPart(uint64_t address, const QString& currentName, const QString& decompiled,
                                             const QString& disassembly) {
    QString block;
    if (!disassembly.isEmpty())
        block = fill(promptText("prompts/bulk_renamer/quick_disassembly.md"), {{QStringLiteral("disassembly"), disassembly}}) +
                QLatin1Char('\n');
    QString part = fill(promptText("prompts/bulk_renamer/quick_function.md"),
                        {{QStringLiteral("address"), hex(address)},
                         {QStringLiteral("current_name"), currentName},
                         {QStringLiteral("decompiled"), decompiled},
                         {QStringLiteral("disassembly_block"), block}});
    if (part.size() > kMaxFunctionChars) part = part.left(kMaxFunctionChars) + QStringLiteral("\n// ... (truncated)\n");
    return part;
}

QString BulkRenamerEngine::quickPrompt(const QStringList& parts, const QString& tmpl) {
    return fill(tmpl.isEmpty() ? promptText("prompts/bulk_renamer/quick.md") : tmpl,
                {{QStringLiteral("functions"), parts.join(QLatin1Char('\n'))}});
}

std::vector<std::vector<int>> BulkRenamerEngine::splitBatches(const std::vector<qsizetype>& partLengths,
                                                              qsizetype headerChars, int batchSize) {
    std::vector<std::vector<int>> out;
    std::vector<int> cur;
    qsizetype chars = headerChars;
    for (int i = 0; i < int(partLengths.size()); ++i) {
        const bool overflow = !cur.empty() && chars + partLengths[size_t(i)] > kMaxPromptChars;
        const bool full = !cur.empty() && int(cur.size()) >= batchSize;
        if (overflow || full) {
            out.push_back(std::move(cur));
            cur.clear();
            chars = headerChars;
        }
        cur.push_back(i);
        chars += partLengths[size_t(i)];
    }
    if (!cur.empty()) out.push_back(std::move(cur));
    return out;
}

QString BulkRenamerEngine::deepTask(uint64_t address, const QString& currentName, const QString& decompiled) {
    return fill(promptText("prompts/bulk_renamer/deep.md"), {{QStringLiteral("address"), hex(address)},
                                                             {QStringLiteral("current_name"), currentName},
                                                             {QStringLiteral("decompiled"), decompiled}});
}

