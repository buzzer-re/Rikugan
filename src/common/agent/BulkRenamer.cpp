// A prompt file without its final newline (prompts/MANIFEST.md).
QString promptText(std::string_view path) {
    QString t = embeddedText(path);
    if (t.endsWith(QLatin1Char('\n'))) t.chop(1);
    return t;
}

// {{name}} substitution in one pass (substituted text is never scanned again).
QString fill(const QString& tmpl, const std::map<QString, QString>& values) {
    QString out;
    out.reserve(tmpl.size());
    qsizetype i = 0;
    while (i < tmpl.size()) {
        const qsizetype open = tmpl.indexOf(QStringLiteral("{{"), i);
        if (open < 0) break;
        const qsizetype close = tmpl.indexOf(QStringLiteral("}}"), open + 2);
        if (close < 0) break;
        const auto it = values.find(tmpl.mid(open + 2, close - open - 2));
        out += QStringView(tmpl).mid(i, (it == values.end() ? close + 2 : open) - i);
        if (it != values.end()) out += it->second;
        i = close + 2;
    }
    out += QStringView(tmpl).mid(i);
    return out;
}

// str.splitlines()
QStringList splitLines(const QString& text) {
    static const QRegularExpression re(QStringLiteral("\r\n|[\n\r\v\f\x1c\x1d\x1e\u0085\u2028\u2029]"));
    QStringList lines = text.split(re);
    if (!lines.isEmpty() && lines.last().isEmpty()) lines.removeLast();
    return lines;
}

bool finished(RenameStatus s) {
    return s == RenameStatus::Completed || s == RenameStatus::Failed || s == RenameStatus::Skipped;
}

QString errorText(const std::exception& e) { return QString::fromUtf8(e.what()); }

// The worker session's state: open failure and the outcome of the prompt in flight.
struct WorkerState {
    std::mutex mu;
    std::condition_variable cv;
    bool openFailed = false;
    QString openError;
    bool done = false;
    OmcSession::PromptOutcome out;
};

class WorkerListener : public OmcListener {
public:
    explicit WorkerListener(std::shared_ptr<WorkerState> st) : st_(std::move(st)) {}
    void onFrame(std::string_view, const std::string&) override {}
    void onHostToolCall(const QJsonObject&) override {}  // the session has no host tools
    void onHostToolCancel(const QString&) override {}
    void onOpenFailed(const QString& error) override {
        std::lock_guard<std::mutex> g(st_->mu);
        st_->openFailed = true;
        st_->openError = error;
        st_->cv.notify_all();
    }

private:
    std::shared_ptr<WorkerState> st_;
};

