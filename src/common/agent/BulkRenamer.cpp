std::shared_ptr<BulkRenamerEngine> BulkRenamerEngine::create(std::shared_ptr<DbContext> db, Options options, Sink sink) {
    return std::shared_ptr<BulkRenamerEngine>(new BulkRenamerEngine(std::move(db), std::move(options), std::move(sink)));
}

BulkRenamerEngine::BulkRenamerEngine(std::shared_ptr<DbContext> db, Options options, Sink sink)
    : db_(std::move(db)), opts_(std::move(options)), sink_(std::move(sink)) {
    opts_.batchSize = std::max(1, opts_.batchSize);
    opts_.maxConcurrent = std::max(1, opts_.maxConcurrent);
    const RikuganConfig& cfg = RikuganConfig::instance();
    model_ = cfg.model;
    thinking_ = cfg.thinking;
    scratchDir_ = db_->scratchDir();
    ctx_ = std::make_shared<ChatContext>();
    ctx_->dbId = db_->dbId;
    ctx_->db = db_;
    ctx_->host = db_->host.get();
    ctx_->registry = &db_->registry;
    ctx_->cache = &db_->cache;
    ctx_->artifactsDir = db_->artifactsDir();
    ctx_->profile = activeProfile();
}

BulkRenamerEngine::~BulkRenamerEngine() = default;

void BulkRenamerEngine::enqueue(const std::vector<RenameJob>& jobs) {
    std::lock_guard<std::mutex> g(mu_);
    for (const RenameJob& j : jobs) {
        jobs_.push_back(j);
        original_[j.address] = j.currentName;
    }
}

void BulkRenamerEngine::start(bool deep) {
    cancelled_ = false;
    {
        std::lock_guard<std::mutex> g(mu_);
        token_ = std::make_shared<CancelToken>();
    }
    resume();
    log(QStringLiteral("Rikugan: bulk renamer started: %1 jobs, mode=%2")
            .arg(pendingIndices().size())
            .arg(deep ? QStringLiteral("deep") : QStringLiteral("quick")));
    std::shared_ptr<BulkRenamerEngine> self = shared_from_this();
    spawnThread([self, deep] {
        if (deep) self->runDeep();
        else self->runQuick();
    });
}

void BulkRenamerEngine::pause() {
    std::lock_guard<std::mutex> g(pauseMu_);
    paused_ = true;
}

void BulkRenamerEngine::resume() {
    {
        std::lock_guard<std::mutex> g(pauseMu_);
        paused_ = false;
    }
    pauseCv_.notify_all();
}

bool BulkRenamerEngine::isPaused() const {
    std::lock_guard<std::mutex> g(pauseMu_);
    return paused_;
}

void BulkRenamerEngine::cancel() {
    cancelled_ = true;
    std::vector<std::shared_ptr<OmcSession>> sessions;
    {
        std::lock_guard<std::mutex> g(mu_);
        token_->cancel();
        sessions.assign(sessions_.begin(), sessions_.end());
    }
    for (const auto& s : sessions) s->abort();
    resume();  // unblock a paused run
    log(QStringLiteral("Rikugan: bulk renamer cancelled"));
}

void BulkRenamerEngine::undoAll() {
    std::shared_ptr<BulkRenamerEngine> self = shared_from_this();
    spawnThread([self] { self->runUndo(); });
}

std::vector<RenameJob> BulkRenamerEngine::jobs() const {
    std::lock_guard<std::mutex> g(mu_);
    return jobs_;
}

bool BulkRenamerEngine::proceed() {
    if (cancelled_) return false;
    std::unique_lock<std::mutex> lk(pauseMu_);
    pauseCv_.wait(lk, [&] { return !paused_ || cancelled_.load(); });
    return !cancelled_;
}

std::vector<int> BulkRenamerEngine::pendingIndices() const {
    std::lock_guard<std::mutex> g(mu_);
    std::vector<int> out;
    for (int i = 0; i < int(jobs_.size()); ++i)
        if (jobs_[size_t(i)].status == RenameStatus::Pending) out.push_back(i);
    return out;
}

int BulkRenamerEngine::finishedCount() const {
    std::lock_guard<std::mutex> g(mu_);
    return int(std::count_if(jobs_.begin(), jobs_.end(), [](const RenameJob& j) { return finished(j.status); }));
}

RenameJob BulkRenamerEngine::job(int index) const {
    std::lock_guard<std::mutex> g(mu_);
    return jobs_[size_t(index)];
}

void BulkRenamerEngine::setJob(int index, const std::function<void(RenameJob&)>& fn) {
    std::lock_guard<std::mutex> g(mu_);
    fn(jobs_[size_t(index)]);
}

void BulkRenamerEngine::emitEvent(RenameEvent e) {
    if (sink_) sink_(e);
}

void BulkRenamerEngine::failJob(int index, const QString& error) {
    RenameJob j;
    setJob(index, [&](RenameJob& r) {
        r.status = RenameStatus::Failed;
        r.error = error;
        j = r;
    });
    emitEvent(RenameEvent{RenameEventType::JobError, j.address, j.currentName, {}, error, 0, 0});
}

void BulkRenamerEngine::trackSession(const std::shared_ptr<OmcSession>& s, bool add) {
    std::lock_guard<std::mutex> g(mu_);
    if (add) sessions_.insert(s);
    else sessions_.erase(s);
}

QString BulkRenamerEngine::runTool(const QString& tool, const QJsonObject& args, bool cancellable) {
    std::shared_ptr<CancelToken> token;
    if (cancellable) {
        std::lock_guard<std::mutex> g(mu_);
        token = token_;
    }
    return ToolDispatcher::runDirect(*db_->host, db_->registry, nullptr, tool, args, token);
}

void BulkRenamerEngine::rename(uint64_t address, const QString& name) {
    runTool(QStringLiteral("rename_function"), QJsonObject{{"address", hex(address)}, {"new_name", name}}, false);
    db_->cache.invalidate();  // runDirect bypasses the dispatcher's cache flush
}

// ---- quick mode ----

void BulkRenamerEngine::runQuick() {
    const std::vector<int> pending = pendingIndices();
    const int total = int(pending.size());

    // Phase 1: decompile every function (sequential: the host serialises them anyway)
    std::vector<std::pair<int, QString>> parts;
    for (int idx : pending) {
        if (!proceed()) break;
        RenameJob j;
        setJob(idx, [&](RenameJob& r) {
            r.status = RenameStatus::Decompiling;
            j = r;
        });
        emitEvent(RenameEvent{RenameEventType::JobStarted, j.address, j.currentName, {}, {}, 0, 0});
        try {
            const QString decomp = runTool(QStringLiteral("decompile_function"), QJsonObject{{"address", hex(j.address)}}, true);
            setJob(idx, [&](RenameJob& r) { r.decompiledCode = decomp; });
            QString disasm;
            try {
                disasm = runTool(QStringLiteral("read_disassembly"), QJsonObject{{"address", hex(j.address)}, {"limit", 100}}, true);
            } catch (const std::exception&) {
            }
            parts.emplace_back(idx, quickFunctionPart(j.address, j.currentName, decomp, disasm));
        } catch (const std::exception& e) {
            failJob(idx, errorText(e));
            log(QStringLiteral("Rikugan: decompile failed for %1: %2").arg(hex(j.address), errorText(e)));
        }
    }

    if (parts.empty()) {
        emitEvent(RenameEvent{RenameEventType::AllDone, 0, {}, {}, {}, 0, total});
        return;
    }

    // Phase 2: batches that fit the context window
    std::vector<qsizetype> lengths;
    lengths.reserve(parts.size());
    for (const auto& p : parts) lengths.push_back(p.second.size());
    const std::vector<std::vector<int>> split =
        splitBatches(lengths, quickPrompt({}, opts_.quickTemplate).size(), opts_.batchSize);
    std::vector<std::vector<std::pair<int, QString>>> batches;
    batches.reserve(split.size());
    for (const std::vector<int>& b : split) {
        std::vector<std::pair<int, QString>> batch;
        for (int i : b) batch.push_back(std::move(parts[size_t(i)]));
        batches.push_back(std::move(batch));
    }
    log(QStringLiteral("Rikugan: quick mode: %1 functions -> %2 sub-batches, max_workers=%3")
            .arg(parts.size())
            .arg(batches.size())
            .arg(opts_.maxConcurrent));

    // Phase 3: the batches on up to max_concurrent worker sessions
    std::atomic<int> completed{0}, counter{0}, next{0};
    const int nWorkers = std::min(opts_.maxConcurrent, int(batches.size()));
    std::vector<std::thread> workers;
    for (int w = 0; w < nWorkers; ++w) {
        workers.emplace_back([&] {
            crash::guardThread();
            QuickWorker worker;
            for (int b = next++; b < int(batches.size()); b = next++) {
                try {
                    runQuickBatch(worker, batches[size_t(b)], total, completed, counter);
                } catch (const std::exception& e) {
                    log(QStringLiteral("Rikugan: quick rename worker error: %1").arg(errorText(e)));
                }
            }
            if (worker.session) {
                trackSession(worker.session, false);
                worker.session->close();
            }
        });
    }
    for (std::thread& t : workers) t.join();

    // completed + failed + skipped, so progress reaches 100% and Start is enabled again
    emitEvent(RenameEvent{RenameEventType::AllDone, 0, {}, {}, {}, finishedCount(), total});
    log(QStringLiteral("Rikugan: bulk renamer quick mode finished"));
}

void BulkRenamerEngine::runQuickBatch(QuickWorker& worker, const std::vector<std::pair<int, QString>>& batch, int total,
                                      std::atomic<int>& completed, std::atomic<int>& counter) {
    if (!proceed()) return;
    const int num = ++counter;

    std::vector<int> indices;
    QStringList parts, addrs;
    for (const auto& [idx, part] : batch) {
        indices.push_back(idx);
        parts << part;
        if (addrs.size() < 3) addrs << hex(job(idx).address);
    }
    const int n = int(indices.size());
    const QString suffix = n > 3 ? QStringLiteral(" +%1 more").arg(n - 3) : QString();

    if (!worker.session) {
        OmcOptions o;
        o.cwd = scratchDir_;
        o.model = model_;
        o.thinking = thinking_;
        o.title = QStringLiteral("bulk rename");
        o.systemPrompt = quickPrompt({}, opts_.quickTemplate).trimmed();
        o.noSession = o.noTools = o.noSkills = o.noMcp = true;
        worker.session = OmcSession::open(o, std::make_shared<WorkerListener>(worker.state));
        trackSession(worker.session, true);
        if (cancelled_) worker.session->abort();
    }

    SubagentInfo info;
    info.name = QStringLiteral("quick_batch_%1").arg(num);
    info.task = QStringLiteral("Quick batch %1 (%2 funcs): %3%4").arg(num).arg(n).arg(addrs.join(QStringLiteral(", ")), suffix);
    info.agentType = QStringLiteral("bulk_rename(quick)");
    info.category = QStringLiteral("bulk_rename");
    info.status = SubagentStatus::Running;
    SubagentRegistry& reg = SubagentRegistry::instance();
    const QString agentId = reg.add(info);
    std::weak_ptr<OmcSession> weak = worker.session;
    reg.setCanceller(agentId, [weak] {
        if (auto s = weak.lock()) s->abort();
    });

    // Fresh single-message prompt: clean context, no history
    const QString prompt = quickPrompt(parts, opts_.quickTemplate);
    log(QStringLiteral("Rikugan: quick batch %1: %2 funcs, %3 chars (~%4tok est)").arg(num).arg(n).arg(prompt.size()).arg(prompt.size() / 2));
    for (int idx : indices) setJob(idx, [](RenameJob& r) { r.status = RenameStatus::Analyzing; });

    auto finishAgent = [&](SubagentStatus st, const QString& summary, int turns) {
        reg.setCanceller(agentId, nullptr);
        reg.update(agentId, [&](SubagentInfo& i) {
            i.status = st;
            i.summary = summary;
            i.turnCount = turns;
            i.completedAt = QDateTime::currentMSecsSinceEpoch();
        });
    };

    try {
        std::shared_ptr<WorkerState> st = worker.state;
        {
            std::lock_guard<std::mutex> g(st->mu);
            st->done = false;
        }
        std::shared_ptr<BulkRenamerEngine> self = shared_from_this();
        worker.session->post([st, prompt, self](OmcSession& s) {
            OmcSession::PromptOutcome out;
            if (self->cancelled_) {
                out.status = QStringLiteral("aborted");
            } else {
                s.request(QJsonObject{{"type", "new_session"}});
                // a fresh session is unnamed: named, omc spends no model call titling it
                s.request(QJsonObject{{"type", "set_session_name"}, {"name", "bulk rename"}});
                out = s.prompt(prompt);
            }
            std::lock_guard<std::mutex> g(st->mu);
            st->out = std::move(out);
            st->done = true;
            st->cv.notify_all();
        });
        OmcSession::PromptOutcome out;
        {
            std::unique_lock<std::mutex> lk(st->mu);
            st->cv.wait(lk, [&] { return st->done || st->openFailed; });
            if (!st->done) throw ToolError(st->openError);
            out = st->out;
        }
        if (out.status == QLatin1String("aborted")) throw ToolError(QStringLiteral("Cancelled"));
        if (out.status == QLatin1String("error"))
            throw ToolError(out.error.isEmpty() ? QStringLiteral("The model call failed") : out.error);
        applyQuickResults(indices, parseQuickReply(out.lastText), agentId);
        int renamed = 0;
        for (int idx : indices)
            if (job(idx).status == RenameStatus::Completed) ++renamed;
        finishAgent(SubagentStatus::Completed, QStringLiteral("Renamed %1/%2 functions").arg(renamed).arg(n), n);
    } catch (const std::exception& e) {
        const QString err = errorText(e);
        for (int idx : indices) failJob(idx, err);
        log(QStringLiteral("Rikugan: quick analysis batch %1 failed: %2").arg(num).arg(err));
        finishAgent(cancelled_ ? SubagentStatus::Cancelled : SubagentStatus::Failed, err, 1);
    }

    completed += n;
    emitEvent(RenameEvent{RenameEventType::BatchProgress, 0, {}, {}, {}, completed.load(), total});
}

void BulkRenamerEngine::applyQuickResults(const std::vector<int>& indices, const std::map<uint64_t, QString>& names,
                                          const QString& agentId) {
    SubagentRegistry& reg = SubagentRegistry::instance();
    int applied = 0;
    const int n = int(indices.size());
    auto progress = [&] {
        reg.update(agentId, [&](SubagentInfo& i) {
            i.summary = QStringLiteral("%1/%2").arg(applied).arg(n);
            i.turnCount = applied;
        });
    };
    for (int idx : indices) {
        const RenameJob j = job(idx);
        const auto it = names.find(j.address);
        if (it == names.end() || it->second.isEmpty()) {
            failJob(idx, QStringLiteral("No name suggested by LLM"));
            continue;
        }
        const QString newName = it->second;
        setJob(idx, [&](RenameJob& r) {
            r.newName = newName;
            r.status = RenameStatus::Renaming;
        });
        try {
            rename(j.address, newName);
            setJob(idx, [](RenameJob& r) { r.status = RenameStatus::Completed; });
            emitEvent(RenameEvent{RenameEventType::JobCompleted, j.address, j.currentName, newName, {}, 0, 0});
        } catch (const std::exception& e) {
            failJob(idx, errorText(e));
            log(QStringLiteral("Rikugan: rename failed for %1: %2").arg(hex(j.address), errorText(e)));
        }
        ++applied;
        progress();
    }
}

// ---- deep mode ----

void BulkRenamerEngine::runDeep() {
    const std::vector<int> pending = pendingIndices();
    const int total = int(pending.size());
    std::atomic<int> completed{0}, next{0};
    const int nWorkers = std::min(opts_.maxConcurrent, total);
    std::vector<std::thread> workers;
    for (int w = 0; w < nWorkers; ++w) {
        workers.emplace_back([&] {
            crash::guardThread();
            for (int k = next++; k < total; k = next++) {
                try {
                    analyzeOne(pending[size_t(k)], total, completed);
                } catch (const std::exception& e) {
                    log(QStringLiteral("Rikugan: deep rename worker error: %1").arg(errorText(e)));
                }
            }
        });
    }
    for (std::thread& t : workers) t.join();
    emitEvent(RenameEvent{RenameEventType::AllDone, 0, {}, {}, {}, finishedCount(), total});
    log(QStringLiteral("Rikugan: bulk renamer deep mode finished"));
}

void BulkRenamerEngine::analyzeOne(int index, int total, std::atomic<int>& completed) {
    if (!proceed()) return;
    SubagentRegistry& reg = SubagentRegistry::instance();
    RenameJob j;
    setJob(index, [&](RenameJob& r) {
        r.status = RenameStatus::Decompiling;
        j = r;
    });
    emitEvent(RenameEvent{RenameEventType::JobStarted, j.address, j.currentName, {}, {}, 0, 0});
    const QString agentName = QStringLiteral("agent_") + j.currentName;

    QString decomp;
    try {
        decomp = runTool(QStringLiteral("decompile_function"), QJsonObject{{"address", hex(j.address)}}, true);
        setJob(index, [&](RenameJob& r) { r.decompiledCode = decomp; });
    } catch (const std::exception& e) {
        failJob(index, errorText(e));
        SubagentInfo info;
        info.name = agentName;
        info.task = QStringLiteral("Deep rename analysis for %1 at %2").arg(j.currentName, hex(j.address));
        info.agentType = QStringLiteral("bulk_rename(deep)");
        info.category = QStringLiteral("bulk_rename");
        info.status = SubagentStatus::Failed;
        info.summary = errorText(e);
        info.completedAt = QDateTime::currentMSecsSinceEpoch();
        reg.add(info);
        return;
    }

    setJob(index, [](RenameJob& r) { r.status = RenameStatus::Analyzing; });
    SubagentSpec spec;
    spec.name = agentName;
    spec.task = deepTask(j.address, j.currentName, decomp);
    spec.agentType = QStringLiteral("bulk_rename(deep)");
    spec.category = QStringLiteral("bulk_rename");
    spec.maxTurns = 10;
    spec.silent = true;
    std::shared_ptr<CancelToken> token;
    {
        std::lock_guard<std::mutex> g(mu_);
        token = token_;
    }
    const SubagentOutcome out = runSubagent(*ctx_, spec, token);
    auto finishAgent = [&](SubagentStatus st, const QString& summary) {
        reg.update(out.id, [&](SubagentInfo& i) {
            i.status = st;
            i.summary = summary;
        });
    };
    if (cancelled_) {
        failJob(index, QStringLiteral("Cancelled"));
        finishAgent(SubagentStatus::Cancelled, QStringLiteral("Cancelled"));
        return;
    }
    if (out.status == QLatin1String("error")) {
        const QString err = out.error.isEmpty() ? QStringLiteral("The subagent failed") : out.error;
        failJob(index, err);
        finishAgent(SubagentStatus::Failed, err);
        return;
    }

    const auto parsed = parseDeepReply(out.text);
    if (!parsed) {
        const QString err = QStringLiteral("No RENAME line found in subagent output");
        failJob(index, err);
        finishAgent(SubagentStatus::Failed, err);
        return;
    }
    const QString newName = parsed->second;
    setJob(index, [&](RenameJob& r) {
        r.newName = newName;
        r.status = RenameStatus::Renaming;
    });
    try {
        rename(j.address, newName);
        setJob(index, [](RenameJob& r) { r.status = RenameStatus::Completed; });
        emitEvent(RenameEvent{RenameEventType::JobCompleted, j.address, j.currentName, newName, {}, 0, 0});
        finishAgent(SubagentStatus::Completed, QStringLiteral("Renamed to %1").arg(newName));
    } catch (const std::exception& e) {
        failJob(index, errorText(e));
        log(QStringLiteral("Rikugan: deep rename failed for %1: %2").arg(hex(j.address), errorText(e)));
        finishAgent(SubagentStatus::Failed, errorText(e));
    }
    const int done = ++completed;
    emitEvent(RenameEvent{RenameEventType::BatchProgress, 0, {}, {}, {}, done, total});
}

// ---- undo ----

void BulkRenamerEngine::runUndo() {
    std::vector<std::pair<int, QString>> toUndo;
    {
        std::lock_guard<std::mutex> g(mu_);
        for (int i = 0; i < int(jobs_.size()); ++i) {
            const RenameJob& j = jobs_[size_t(i)];
            const auto it = original_.find(j.address);
            if (j.status == RenameStatus::Completed && it != original_.end()) toUndo.emplace_back(i, it->second);
        }
    }
    const int total = int(toUndo.size());
    int reverted = 0;
    for (const auto& [idx, original] : toUndo) {
        const RenameJob j = job(idx);
        try {
            rename(j.address, original);
            ++reverted;
            setJob(idx, [](RenameJob& r) {
                r.status = RenameStatus::Pending;
                r.newName.clear();
            });
            emitEvent(RenameEvent{RenameEventType::JobCompleted, j.address, original, {}, {}, 0, 0});
        } catch (const std::exception& e) {
            log(QStringLiteral("Rikugan: failed to revert %1: %2").arg(hex(j.address), errorText(e)));
            emitEvent(RenameEvent{RenameEventType::JobError, j.address, j.currentName, {},
                                  QStringLiteral("Undo failed: %1").arg(errorText(e)), 0, 0});
        }
    }
    // completion resets the progress
    emitEvent(RenameEvent{RenameEventType::AllDone, 0, {}, {}, {}, 0, total});
    log(QStringLiteral("Rikugan: undo complete: reverted %1/%2 renames").arg(reverted).arg(total));
}

