QString renameStatusName(RenameStatus s) {
    switch (s) {
    case RenameStatus::Pending: return QStringLiteral("pending");
    case RenameStatus::Decompiling: return QStringLiteral("decompiling");
    case RenameStatus::Analyzing: return QStringLiteral("analyzing");
    case RenameStatus::Renaming: return QStringLiteral("renaming");
    case RenameStatus::Completed: return QStringLiteral("completed");
    case RenameStatus::Skipped: return QStringLiteral("skipped");
    case RenameStatus::Failed: return QStringLiteral("failed");
    }
    return {};
}

// One quick-mode worker: an omc session reused (new_session) for each of its batches.
struct BulkRenamerEngine::QuickWorker {
    std::shared_ptr<OmcSession> session;
    std::shared_ptr<WorkerState> state = std::make_shared<WorkerState>();
};

